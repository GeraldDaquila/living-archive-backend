"""Regression coverage for the Basic Inquiry visitor-language boundary."""

import main


def test_ordinary_handoff_language_is_not_machine_facing():
    examples = (
        "A clear handoff helps the next person continue without losing context.",
        "A team handoff can affect the quality and timing of another team's work.",
        "A handoff between teams should preserve context and responsibility.",
        "For example, a delayed handoff can affect the next team's work.",
    )
    assert all(
        not main._basic_inquiry_has_internal_implementation_language(text)
        for text in examples
    )


def test_machine_facing_handoff_metadata_is_rejected():
    examples = (
        "The handoff payload includes the route source.",
        "The handoff endpoint forwards the request to the mirror.",
        "The provider handoff is pending.",
        "The handoff between services uses a route adapter.",
        "The request is sent through the handoff to the provider.",
    )
    assert all(
        main._basic_inquiry_has_internal_implementation_language(text)
        for text in examples
    )


def test_other_internal_implementation_terms_remain_rejected():
    examples = (
        "The canonical evidence supports this conclusion.",
        "The provider bank selected a model.",
        "The route source is recorded in implementation metadata.",
        "The response was generated by USE.",
    )
    assert all(
        main._basic_inquiry_has_internal_implementation_language(text)
        for text in examples
    )
